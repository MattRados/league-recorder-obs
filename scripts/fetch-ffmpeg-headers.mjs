// Fetches the headers of FFmpeg 6.1.1, the version of the FFmpeg libraries OBS bundles (avcodec-60,
// avformat-60, avutil-58, swresample-4, swscale-7 in resources/obs/bin/64bit), so native/media can be
// compiled against them: the public headers of FFmpeg's official source release, into out/ffmpeg-sdk.
// Import libraries come from the bundled DLLs (scripts/build-native.mjs). Nothing from the download ships.
//
//   node scripts/fetch-ffmpeg-headers.mjs           only if missing
//   node scripts/fetch-ffmpeg-headers.mjs --force   re-download

import { execFileSync } from 'child_process'
import { createHash } from 'crypto'
import { existsSync, mkdirSync, mkdtempSync, readdirSync, renameSync, rmSync, writeFileSync } from 'fs'
import { tmpdir } from 'os'
import { join } from 'path'

const VERSION = '6.1.1'
const URL = `https://ffmpeg.org/releases/ffmpeg-${VERSION}.tar.xz`
// Pinned after the first download
const SHA256 = '8684f4b00f94b85461884c3719382f1261f0d9eb3d59640a1f4ac0873616f968'
const LIBS = ['libavcodec', 'libavformat', 'libavutil', 'libswresample', 'libswscale']

const target = join(import.meta.dirname, '..', 'out', 'ffmpeg-sdk')
if (existsSync(join(target, 'libavformat', 'avformat.h')) && !process.argv.includes('--force')) {
  console.log('FFmpeg headers already present')
  process.exit(0)
}

console.log('Downloading', URL)
const res = await fetch(URL)
if (!res.ok) throw new Error(`${URL}: HTTP ${res.status}`)
const archive = Buffer.from(await res.arrayBuffer())
const actual = createHash('sha256').update(archive).digest('hex')
if (SHA256 && actual !== SHA256) throw new Error(`Checksum mismatch: expected ${SHA256}, got ${actual}`)
console.log('sha256', actual)

const work = mkdtempSync(join(tmpdir(), 'ffmpeg-sdk-'))
try {
  const archivePath = join(work, 'src.tar.xz')
  writeFileSync(archivePath, archive)
  const tar = join(process.env.SystemRoot ?? 'C:\\Windows', 'System32', 'tar.exe')
  execFileSync(tar, ['-xf', archivePath, '-C', work, ...LIBS.map((l) => `ffmpeg-${VERSION}/${l}`)])
  rmSync(target, { recursive: true, force: true })
  mkdirSync(target, { recursive: true })
  for (const lib of LIBS) {
    // Only the headers are needed
    const from = join(work, `ffmpeg-${VERSION}`, lib)
    const to = join(target, lib)
    mkdirSync(to, { recursive: true })
    for (const f of readdirSync(from, { recursive: true })) {
      const name = String(f)
      if (!name.endsWith('.h')) continue
      mkdirSync(join(to, name, '..'), { recursive: true })
      renameSync(join(from, name), join(to, name))
    }
  }
  // Generated by FFmpeg's configure, so not in the source release: the values for x86-64 Windows
  writeFileSync(
    join(target, 'libavutil', 'avconfig.h'),
    '/* Generated for x86-64 Windows (FFmpeg normally writes this at configure time) */\n' +
      '#ifndef AVUTIL_AVCONFIG_H\n#define AVUTIL_AVCONFIG_H\n#define AV_HAVE_BIGENDIAN 0\n#define AV_HAVE_FAST_UNALIGNED 1\n#endif\n'
  )
  console.log('FFmpeg headers ready in', target)
} finally {
  rmSync(work, { recursive: true, force: true })
}
